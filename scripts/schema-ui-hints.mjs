// schema-ui-hints — derive the editor's presentation hints from schema/*.json.
//
// A schema field may carry `"ui": "wide"` (ADR-32; the only hint that survives).
// The hint is OURS: it never reaches a FileClass file (schema-gen's fcField does
// not read it). The bundled plugin cannot read schema/ at runtime, so schema-gen
// also writes the hints into src/editor/generatedUiHints.ts, and schema-check
// verifies that file against a fresh render — the same two-script contract as
// every other generated artifact.
//
// Hints are keyed by the FileClass that declares them (`fc-<entity>`), not by
// bare field name, so a user's own FileClass with a `tagline` field is not widened.

export const UI_HINT_FILE = 'src/editor/generatedUiHints.ts';
export const VALID_UI = new Set(['wide']);

/** schemas -> { 'fc-<entity>': { <field>: 'wide' } }; throws on an unknown `ui`. */
export function collectUiHints(schemas) {
  const out = {};
  for (const s of schemas) {
    for (const f of s.fields) {
      if (f.ui === undefined) continue;
      if (!VALID_UI.has(f.ui)) {
        throw new Error(
          `schema/${s.entity}.json: ${s.entity}.${f.name} has unknown "ui": ${JSON.stringify(f.ui)}` +
            ` (allowed: ${[...VALID_UI].map((v) => JSON.stringify(v)).join(', ')})`,
        );
      }
      (out[`fc-${s.entity}`] ??= {})[f.name] = f.ui;
    }
  }
  return out;
}

/** The TypeScript source of src/editor/generatedUiHints.ts for `hints`. */
export function renderUiHintsModule(hints) {
  const classes = Object.keys(hints).sort();
  const body = classes
    .map((c) => {
      const fields = Object.keys(hints[c]).sort().map((n) => `\t\t${JSON.stringify(n)}: "${hints[c][n]}",`);
      return `\t${JSON.stringify(c)}: {\n${fields.join('\n')}\n\t},`;
    })
    .join('\n');
  return `/**
 * GENERATED by \`npm run schema:gen\` from schema/*.json — do not edit.
 * \`npm run schema:check\` fails if this file drifts from the schema.
 *
 * The \`ui\` presentation hints (ADR-32), keyed by the FileClass that declares
 * them. They live here, never in a FileClass file.
 */

import type { UiHintsByFileClass } from "editor/fieldModel";

export const GENERATED_UI_HINTS: UiHintsByFileClass = {${body ? `\n${body}\n` : ''}};
`;
}
